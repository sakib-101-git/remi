#!/usr/bin/env python3
"""Regenerate THIRD_PARTY_LICENSES.md from installed package metadata (backend venv + frontend node_modules)."""
from __future__ import annotations

import json
import re
import sys
from importlib import metadata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PERMISSIVE = re.compile(r"MIT|BSD|Apache|ISC|PSF|Python Software|0BSD|Unlicense|CC0|Zlib|MPL|BlueOak|CC-BY-4.0|Python-2.0", re.I)

CLASSIFIER_MAP = {
    "MIT License": "MIT",
    "BSD License": "BSD",
    "Apache Software License": "Apache-2.0",
    "Python Software Foundation License": "PSF-2.0",
    "Mozilla Public License 2.0 (MPL 2.0)": "MPL-2.0",
    "ISC License (ISCL)": "ISC",
}

# Packages that ship no licence metadata; verified against the upstream repository.
OVERRIDES = {"py-rust-stemmers": "MIT (upstream qdrant/py-rust-stemmers; metadata missing)"}

EXTRA = [
    ("BAAI/bge-small-en-v1.5 (embedding model, via fastembed)", "MIT", "Local knowledge-base embeddings"),
    ("Inter, Space Grotesk, JetBrains Mono (Google Fonts)", "OFL-1.1", "UI typography (loaded from Google Fonts)"),
    ("Playwright browsers (Chromium)", "Apache-2.0 / BSD", "E2E tests, screenshots, PDF rendering (dev only)"),
    ("Mermaid CLI (@mermaid-js/mermaid-cli, via npx)", "MIT", "Diagram rendering for docs (dev only)"),
]


def _py_license(dist: metadata.Distribution) -> str:
    meta = dist.metadata
    expr = meta.get("License-Expression")
    if expr:
        return expr.strip()
    classifiers = [c.split(" :: ")[-1] for c in meta.get_all("Classifier") or [] if c.startswith("License :: OSI Approved")]
    if classifiers:
        return " / ".join(CLASSIFIER_MAP.get(c, c) for c in classifiers)
    lic = (meta.get("License") or "").strip()
    if lic and len(lic) < 60:
        return lic
    if lic:
        for key in ("MIT", "Apache", "BSD"):
            if key in lic:
                return key + (" (see package)" if key != "MIT" else "")
    return "UNKNOWN"


def _norm(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def python_rows() -> tuple[list[tuple[str, str, str]], list[tuple[str, str, str]]]:
    direct = []
    for line in (ROOT / "backend" / "requirements.txt").read_text().splitlines() + (ROOT / "backend" / "requirements-dev.txt").read_text().splitlines():
        line = line.split("#")[0].strip()
        if not line or line.startswith("-r"):
            continue
        direct.append(_norm(re.split(r"[\[=<>~]", line)[0]))
    rows, transitive = [], []
    for dist in sorted(metadata.distributions(), key=lambda d: _norm(d.metadata["Name"])):
        name = dist.metadata["Name"]
        if _norm(name) in ("pip", "setuptools", "wheel"):
            continue
        row = (name, dist.version, OVERRIDES.get(_norm(name)) or _py_license(dist))
        (rows if _norm(name) in direct else transitive).append(row)
    return rows, transitive


def node_rows() -> tuple[list[tuple[str, str, str]], list[tuple[str, str, str]]]:
    pkg = json.loads((ROOT / "frontend" / "package.json").read_text())
    direct_names = set(pkg.get("dependencies", {})) | set(pkg.get("devDependencies", {}))
    rows, transitive, seen = [], [], set()
    for manifest in sorted((ROOT / "frontend" / "node_modules").glob("**/package.json")):
        rel = manifest.relative_to(ROOT / "frontend" / "node_modules").parts
        if "node_modules" in rel[:-1] and rel.count("node_modules") > 0 and len(rel) > 3:
            continue
        try:
            data = json.loads(manifest.read_text())
        except (ValueError, UnicodeDecodeError):
            continue
        name, version = data.get("name"), data.get("version")
        if not name or not version or (name, version) in seen:
            continue
        expected = "/".join(p for p in rel[:-1] if p != "node_modules")
        if expected != name:
            continue
        seen.add((name, version))
        lic = data.get("license")
        if isinstance(lic, dict):
            lic = lic.get("type")
        if not lic and isinstance(data.get("licenses"), list):
            lic = " / ".join(x.get("type", "") for x in data["licenses"])
        row = (name, version, lic or "UNKNOWN")
        (rows if name in direct_names else transitive).append(row)
    return rows, transitive


def table(rows: list[tuple[str, str, str]]) -> list[str]:
    return ["| Package | Version | License |", "|---|---|---|"] + [f"| {n} | {v} | {lic} |" for n, v, lic in rows]


def main() -> int:
    py, py_t = python_rows()
    js, js_t = node_rows()
    flagged = [r for r in py + py_t + js + js_t if not PERMISSIVE.search(r[2])]
    out = [
        "# Third-party licenses",
        "",
        "Remi is released under the MIT License (see `LICENSE`). It uses only free, open-source components under permissive licenses.",
        "This file is generated by `scripts/gen_licenses.py` from the installed package metadata.",
        "",
        "## Python - direct dependencies (`backend/requirements*.txt`)",
        "",
        *table(py),
        "",
        "## JavaScript - direct dependencies (`frontend/package.json`)",
        "",
        *table(js),
        "",
        "## Models, fonts and tools",
        "",
        "| Component | License | Used for |",
        "|---|---|---|",
        *[f"| {n} | {lic} | {u} |" for n, lic, u in EXTRA],
        "",
        "## Licence review",
        "",
    ]
    if flagged:
        out += ["Packages whose metadata does not state a common permissive licence (checked manually):", "", *table(flagged), ""]
    else:
        out += ["Every package below reports a permissive licence (MIT, BSD, Apache-2.0, ISC, PSF, MPL-2.0, CC0 and similar). No copyleft (GPL/AGPL) dependency is used.", ""]
    out += [
        "## Python - transitive dependencies",
        "",
        *table(py_t),
        "",
        "## JavaScript - transitive dependencies",
        "",
        "<details><summary>" + f"{len(js_t)} packages" + "</summary>",
        "",
        *table(js_t),
        "",
        "</details>",
        "",
    ]
    (ROOT / "THIRD_PARTY_LICENSES.md").write_text("\n".join(out))
    print(f"THIRD_PARTY_LICENSES.md: {len(py)}+{len(py_t)} Python, {len(js)}+{len(js_t)} JS packages; {len(flagged)} need a manual look")
    for r in flagged:
        print("  check:", *r)
    return 0


if __name__ == "__main__":
    sys.exit(main())
